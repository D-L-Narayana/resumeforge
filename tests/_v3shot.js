const {chromium}=require('playwright');
(async function(){
const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1440,height:900}});
await p.goto('http://localhost:8043/index.html',{waitUntil:'domcontentloaded'});
await p.waitForTimeout(2400);
const r={compare:await p.locator('.compare').count(),wall:await p.locator('.wall-card').count(),orbit:await p.locator('.orbit-chip').count()};
await p.evaluate(function(){document.querySelector('.compare').scrollIntoView({block:'center'});});
await p.waitForTimeout(2200);
const box=await p.locator('.compare').boundingBox();
await p.mouse.move(box.x+box.width*0.5,box.y+box.height*0.5);
await p.mouse.down();
await p.mouse.move(box.x+box.width*0.75,box.y+box.height*0.5,{steps:8});
await p.mouse.up();
await p.waitForTimeout(300);
r.handleLeft=await p.evaluate(function(){return document.querySelector('.cmp-handle').style.left;});
await p.screenshot({path:'/tmp/v3a.png'});
await p.evaluate(function(){document.querySelector('.wall').scrollIntoView({block:'center'});});
await p.waitForTimeout(1200);
await p.screenshot({path:'/tmp/v3b.png'});
const p2=await b.newPage({viewport:{width:1440,height:900}});
await p2.goto('http://localhost:8043/salary.html',{waitUntil:'domcontentloaded'});
await p2.waitForTimeout(1900);
r.scrambleFinal=await p2.evaluate(function(){var h=document.querySelector('.page-head h1');return h?h.textContent:'none';});
console.log('V3 '+JSON.stringify(r));
await b.close();
})().catch(function(e){console.error('ERR '+e.message);process.exit(1);});
